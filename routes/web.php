    Route::get('/panel', [DashboardController::class, 'index'])->name('dashboard');
    Route::get('/panel/estado', [DashboardController::class, 'status'])->name('dashboard.status');
    Route::get('/equipos/estados', [DashboardController::class, 'deviceStatuses'])->name('devices.statuses');
