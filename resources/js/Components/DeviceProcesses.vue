<script setup lang="ts">
import { computed, ref, watch } from 'vue';
import { ChevronDown, Search } from '@lucide/vue';
import ProcessInfoModal from '@/Components/ProcessInfoModal.vue';
import type { ProcessInformation } from '@/types/nodo';
import type { Process } from '@/types/nodo';
import { dateTime } from '@/types/nodo';
import { formatUnixSeconds } from '@/Lib/displayTimezone';

const props = defineProps<{
  processes: Process[];
  totalCount?: number | null;
  capturedAt: string | null;
  online: boolean;
  canCommand: boolean;
  deviceUuid: string;
}>();
const emit = defineEmits<{ terminate: [process: Process] }>();

type Group = { id: string; title: string; executable: string; items: Process[]; totalMb: number };
const expanded = ref(false);
const expandedGroups = ref<Set<string>>(new Set());
const search = ref('');
const showAll = ref(false);
const selectedProcess = ref<string | null>(null);
const knowledgeCache = new Map<string, ProcessInformation>();
function openInformation(process: Process): void { selectedProcess.value = process.name; }
function cacheInformation(name: string, result: ProcessInformation): void {
  if (result.source === 'unavailable') return;
  if (knowledgeCache.size >= 50) knowledgeCache.delete(knowledgeCache.keys().next().value ?? '');
  knowledgeCache.set(name.toLowerCase(), result);
}


// The group key is generated by the Windows agent from path + session. Older
// agents have no group identity: never merge their processes by filename alone.
const groups = computed<Group[]>(() => {
  const map = new Map<string, Group>();
  for (const item of props.processes) {
    const validKey = /^[a-f0-9]{32}$/.test(item.group_key ?? '') ? item.group_key : null;
    const key = validKey ?? `legacy:${item.pid}:${item.started_at}`;
    let group = map.get(key);
    if (!group) {
      group = { id: key, title: item.display_name?.trim() || item.name,
        executable: item.name, items: [], totalMb: 0 };
      map.set(key, group);
    }
    group.items.push(item);
    group.totalMb += Number(item.memory_mb) || 0;
  }
  return [...map.values()].sort((a, b) => b.totalMb - a.totalMb);
});
const filtered = computed(() => {
  const query = search.value.trim().toLocaleLowerCase();
  return groups.value.filter(group => !query ||
    group.title.toLocaleLowerCase().includes(query) ||
    group.executable.toLocaleLowerCase().includes(query) ||
    group.items.some(p => p.name.toLocaleLowerCase().includes(query) || String(p.pid).includes(query)));
});
const visible = computed(() => showAll.value || search.value.trim()
  ? filtered.value : filtered.value.slice(0, 15));
const coverageIncomplete = computed(() =>
  props.totalCount != null && props.totalCount > props.processes.length);
function toggleGroup(id: string): void {
  const next = new Set(expandedGroups.value);
  if (next.has(id)) next.delete(id);
  else next.add(id);
  expandedGroups.value = next;
}
function isExpanded(id: string): boolean { return expandedGroups.value.has(id); }
function memory(mb: number): string {
  return `${mb.toLocaleString('es-AR', { maximumFractionDigits: 1 })} MiB`;
}
watch(expanded, open => {
  if (!open) { search.value = ''; showAll.value = false; expandedGroups.value = new Set(); }
});
watch(() => props.capturedAt, () => { expandedGroups.value = new Set(); });
</script>

<template>
  <section class="surface-panel process-panel" aria-labelledby="device-processes-title">
    <div class="section-head process-heading">
      <div>
        <h2 id="device-processes-title">Aplicaciones y procesos <span class="section-count">{{ processes.length }}</span></h2>
        <p>Última captura: {{ dateTime(capturedAt) }}</p>
      </div>
      <button type="button" class="button button-secondary" :aria-expanded="expanded"
        aria-controls="device-processes-content" @click="expanded = !expanded">
        {{ expanded ? 'Contraer' : 'Ver procesos' }}
        <ChevronDown :size="16" class="expand-chevron" :class="{ 'is-open': expanded }" aria-hidden="true" />
      </button>
    </div>
    <div v-if="expanded" id="device-processes-content">
      <div class="process-toolbar">
        <p class="muted">{{ filtered.length }} grupos · {{ processes.length }} procesos capturados
          <template v-if="totalCount !== null && totalCount !== undefined"> de {{ totalCount }} observados</template>
        </p>
        <label class="search-field compact-search">
          <Search :size="16" aria-hidden="true" />
          <input v-model="search" type="search" placeholder="Buscar aplicación, ejecutable o PID"
            aria-label="Buscar por aplicación, ejecutable o PID" />
        </label>
      </div>
      <p v-if="coverageIncomplete" class="process-coverage-warning" role="status">
        La captura es parcial: se muestran {{ processes.length }} de {{ totalCount }} procesos observados.
        El número de procesos por aplicación y la RAM acumulada pueden ser inferiores a los reales.
      </p>
      <p v-else-if="totalCount == null && processes.length" class="process-coverage-note">
        El agente no informó la cobertura de la captura. Los grupos reflejan únicamente los procesos recibidos.
      </p>
      <div v-if="!visible.length" class="empty-tiny">
        <p>{{ !online ? 'Equipo desconectado.' : search ? 'No hay coincidencias.' : 'Sin inventario reciente de procesos.' }}</p>
      </div>
      <div v-else class="table-scroll process-table-scroll">
        <table class="data-table process-group-table">
          <thead><tr><th>Aplicación / proceso</th><th>PID / cantidad</th><th>Inicio</th><th>Memoria residente</th><th class="align-right">Acción</th></tr></thead>
          <tbody v-for="group in visible" :key="group.id">
            <tr class="process-group-row">
              <td>
                <button type="button" class="process-group-toggle" :aria-expanded="isExpanded(group.id)" @click="toggleGroup(group.id)">
                  <ChevronDown :size="15" class="expand-chevron" :class="{ 'is-open': isExpanded(group.id) }" aria-hidden="true" />
                  <span class="process-group-title">{{ group.title }}<span v-if="group.items.length > 1"> ({{ group.items.length }})</span></span>
                </button>
                <span v-if="group.title !== group.executable" class="process-group-executable">{{ group.executable }}</span>
              </td>
              <td class="cell-secondary">{{ group.items.length }} {{ group.items.length === 1 ? 'proceso' : 'procesos' }}</td>
              <td class="cell-secondary">—</td>
              <td class="number-cell process-total-memory">{{ memory(group.totalMb) }}</td>
              <td class="align-right cell-secondary">—</td>
            </tr>
            <tr v-for="process in (isExpanded(group.id) ? group.items : [])"
              :key="`${process.pid}-${process.started_at}`" class="process-child-row">
              <td class="process-child-name"><button type="button" class="process-child-info" :aria-label="`Ver información de ${process.name}`" @click="openInformation(process)">{{ process.name }}</button></td>
              <td class="mono cell-secondary">{{ process.pid }}</td>
              <td class="cell-secondary nowrap">{{ formatUnixSeconds(process.started_at) }}</td>
              <td class="number-cell">{{ memory(Number(process.memory_mb)) }}</td>
              <td class="align-right"><button type="button" class="button button-text-danger"
                :disabled="!canCommand || !process.can_terminate" @click="emit('terminate', process)">Finalizar</button></td>
            </tr>
          </tbody>
        </table>
      </div>
      <p class="process-memory-note">RAM residente acumulada (working set). Puede incluir memoria compartida contada varias veces. Los grupos se basan en el ejecutable y la sesión de Windows, no necesariamente en ventanas de una misma aplicación.</p>
      <div v-if="!search.trim() && filtered.length > 15" class="process-footer">
        <span class="muted">Mostrando {{ visible.length }} de {{ filtered.length }} grupos</span>
        <button type="button" class="button button-secondary" @click="showAll = !showAll">
          {{ showAll ? 'Mostrar menos' : `Mostrar los ${filtered.length} grupos` }}
        </button>
      </div>
    </div>
    <p v-else class="process-collapsed-hint">Expande la lista para consultar los procesos y sus detalles.</p>
    <ProcessInfoModal v-if="selectedProcess" :key="`${deviceUuid}-${selectedProcess}`"
      :process-name="selectedProcess" :device-uuid="deviceUuid"
      :initial-result="knowledgeCache.get(selectedProcess.toLowerCase())"
      @resolved="cacheInformation" @close="selectedProcess = null" />
  </section>
</template>
